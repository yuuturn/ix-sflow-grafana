-- ---------------------------------------------------------------------------
-- sFlow traffic warehouse: pmacct(sfacctd) -> PostgreSQL -> Grafana
--
-- Everything is stored in UTC. pmacct runs with TZ=UTC and the session
-- timezone is UTC, so stamp_inserted is UTC wall-clock in a
-- `timestamp without time zone` column (that is what pmacct's schema wants).
-- Grafana renders it in the viewer's timezone.
--
-- Layering, and why:
--
--   flows      pmacct's raw 5-min aggregates (table_version 9 layout)
--   v_flows    + direction + ASN labels, with an inline fallback lookup
--   flow_5m    rollup: one row per (bucket, direction, src AS, dst AS,
--              host, service port). This is what dashboards read.
--   ip_asn     IP -> ASN dictionary, so enrichment is a hash join instead of
--              ~100 us of btree probes per row on a Raspberry Pi.
--
-- Measured on the Pi 4: a 24 h Sankey over 100k raw rows took 16.6 s through
-- v_flows and ~2.8 s with the dictionary; reading the rollup it is ~100 ms,
-- and the rollup row count does not grow with sampling rate.
-- ---------------------------------------------------------------------------

SET TIME ZONE 'UTC';

-- ---------------------------------------------------------------------------
-- 1. Raw flow table
--
-- Column layout MUST match what this sfacctd build writes. Ubuntu's package
-- is compiled with --enable-l2, which changes the v9 layout: `vlan` becomes
-- `vlan_in` and `vlan_out` is added. The authoritative list is the INSERT
-- sfacctd emits:
--
--   INSERT INTO flows (stamp_updated, stamp_inserted, vlan_in, ip_src,
--     ip_dst, as_src, as_dst, port_src, port_dst, tcp_flags, tos, ip_proto,
--     tag, class_id, mac_src, mac_dst, packets, bytes, flows) VALUES ...
--
-- and the upsert key is the same minus tcp_flags. Do not rename columns:
-- sfacctd builds its statements from this layout. Extra columns below are
-- generated by Postgres and never written by pmacct.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS flows (
    tag             BIGINT      NOT NULL DEFAULT 0,
    class_id        CHAR(16)    NOT NULL DEFAULT ' ',
    mac_src         macaddr     NOT NULL DEFAULT '0:0:0:0:0:0',
    mac_dst         macaddr     NOT NULL DEFAULT '0:0:0:0:0:0',
    vlan_in         INT         NOT NULL DEFAULT 0,
    as_src          BIGINT      NOT NULL DEFAULT 0,
    as_dst          BIGINT      NOT NULL DEFAULT 0,
    ip_src          inet        NOT NULL DEFAULT '0.0.0.0',
    ip_dst          inet        NOT NULL DEFAULT '0.0.0.0',
    port_src        INT         NOT NULL DEFAULT 0,
    port_dst        INT         NOT NULL DEFAULT 0,
    tcp_flags       SMALLINT    NOT NULL DEFAULT 0,
    ip_proto        SMALLINT    NOT NULL DEFAULT 0,
    tos             INT         NOT NULL DEFAULT 0,
    packets         INT         NOT NULL,
    bytes           BIGINT      NOT NULL,
    flows           INT         NOT NULL DEFAULT 0,
    stamp_inserted  TIMESTAMP   NOT NULL DEFAULT '0001-01-01 00:00:00',
    stamp_updated   TIMESTAMP,
    CONSTRAINT flows_pk PRIMARY KEY (
        tag, class_id, mac_src, mac_dst, vlan_in, as_src, as_dst,
        ip_src, ip_dst, port_src, port_dst, ip_proto, tos, stamp_inserted
    )
);

CREATE INDEX IF NOT EXISTS flows_stamp_idx ON flows (stamp_inserted DESC);
CREATE INDEX IF NOT EXISTS flows_src_idx   ON flows (ip_src);
CREATE INDEX IF NOT EXISTS flows_dst_idx   ON flows (ip_dst);

-- ---------------------------------------------------------------------------
-- 2. IP -> ASN ranges (built from a keyless public source, see scripts/)
--    Numbers are the unsigned integer value of the address, so IPv4 and IPv6
--    share one column without colliding (IPv4 < 2^32 < IPv6).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS asn_range (
    ip_start NUMERIC(40,0) NOT NULL,
    ip_end   NUMERIC(40,0) NOT NULL,
    asn      BIGINT        NOT NULL,
    org      TEXT          NOT NULL DEFAULT '',
    country  TEXT          NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS asn_range_start_idx ON asn_range (ip_start);
CREATE UNIQUE INDEX IF NOT EXISTS asn_range_uniq_idx ON asn_range (ip_start, ip_end);

CREATE TABLE IF NOT EXISTS asn_meta (
    key        TEXT PRIMARY KEY,
    value      TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- 3. Helpers (created before the generated columns / views that use them)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION ip2num(ip inet)
RETURNS NUMERIC
LANGUAGE sql IMMUTABLE STRICT AS $$
    -- Unsigned integer value of an address. inet_send() gives the wire format:
    -- 1 byte family, 1 byte netmask, 1 byte is_cidr, 1 byte address length,
    -- then the address bytes.
    SELECT CASE family(ip)
        WHEN 4 THEN
            (split_part(host(ip), '.', 1)::bigint << 24)
          + (split_part(host(ip), '.', 2)::bigint << 16)
          + (split_part(host(ip), '.', 3)::bigint << 8)
          +  split_part(host(ip), '.', 4)::bigint
        WHEN 6 THEN
            -- Every operand is cast to numeric BEFORE multiplying. The literal
            -- 4294967296 fits in bigint, so `bigint * 4294967296` would be done
            -- in bigint arithmetic and overflow for any word >= 2^31
            -- (e.g. 2001:db8:aaaa:bbbb:8cb6:... -> 'bigint out of range').
            (('x' || encode(substring(inet_send(ip) FROM 5  FOR 4), 'hex'))::bit(32)::bigint)::numeric * 79228162514264337593543950336
          + (('x' || encode(substring(inet_send(ip) FROM 9  FOR 4), 'hex'))::bit(32)::bigint)::numeric * 18446744073709551616
          + (('x' || encode(substring(inet_send(ip) FROM 13 FOR 4), 'hex'))::bit(32)::bigint)::numeric * 4294967296
          +  (('x' || encode(substring(inet_send(ip) FROM 17 FOR 4), 'hex'))::bit(32)::bigint)::numeric
    END;
$$;

-- RFC1918 / CGNAT / loopback / ULA / link-local
CREATE OR REPLACE FUNCTION is_private(ip inet)
RETURNS boolean
LANGUAGE sql IMMUTABLE STRICT AS $$
    SELECT ip << '10.0.0.0/8'::inet
        OR ip << '172.16.0.0/12'::inet
        OR ip << '192.168.0.0/16'::inet
        OR ip << '100.64.0.0/10'::inet
        OR ip << '127.0.0.0/8'::inet
        OR ip << 'fc00::/7'::inet
        OR ip << 'fe80::/10'::inet;
$$;

-- Exact lookup: ranges are sorted and non-overlapping, so the row with the
-- greatest ip_start <= x is the only candidate. One btree probe (~100 us).
CREATE OR REPLACE FUNCTION asn_lookup(x NUMERIC)
RETURNS TABLE (asn BIGINT, org TEXT, country TEXT)
LANGUAGE sql STABLE AS $$
    SELECT CASE WHEN r.ip_end >= x THEN r.asn ELSE 0 END,
           CASE WHEN r.ip_end >= x THEN r.org ELSE '' END,
           CASE WHEN r.ip_end >= x THEN r.country ELSE '' END
    FROM asn_range r
    WHERE r.ip_start <= x
    ORDER BY r.ip_start DESC
    LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION proto_name(p SMALLINT)
RETURNS TEXT
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE p
        WHEN 1  THEN 'ICMP'
        WHEN 6  THEN 'TCP'
        WHEN 17 THEN 'UDP'
        WHEN 47 THEN 'GRE'
        WHEN 50 THEN 'ESP'
        WHEN 51 THEN 'AH'
        WHEN 58 THEN 'ICMPv6'
        WHEN 132 THEN 'SCTP'
        ELSE p::text
    END;
$$;

-- ---------------------------------------------------------------------------
-- 4. What counts as "internal"
--
-- RFC1918 alone is not enough on a dual-stack LAN: IPv6 hosts get global
-- addresses from the RA prefix, so they look public and would be classified
-- as `transit`. Keep the internal prefixes in a table instead, seeded with
-- RFC1918/ULA plus the LAN prefix the IX2207 advertises.
--
-- Update the LAN row if the ISP delegates a different prefix (DHCPv6-PD
-- renewal, ISP change):
--   DELETE FROM lan_prefix WHERE note LIKE 'LAN%';
--   INSERT INTO lan_prefix VALUES ('2001:db8:aaaa:cccc::/64', 'LAN');
--   TRUNCATE ip_asn;   -- force the dictionary to be rebuilt
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS lan_prefix (
    prefix cidr PRIMARY KEY,
    note   TEXT NOT NULL DEFAULT ''
);

INSERT INTO lan_prefix (prefix, note) VALUES
    ('10.0.0.0/8',              'RFC1918'),
    ('172.16.0.0/12',           'RFC1918'),
    ('192.168.0.0/16',          'RFC1918'),
    ('100.64.0.0/10',           'CGNAT'),
    ('127.0.0.0/8',             'loopback'),
    ('fc00::/7',                'ULA'),
    ('fe80::/10',               'link-local')
    -- LAN 側の IPv6 プレフィックスはサイト固有なので既定では入れていない。
    -- 未設定だと LAN の IPv6 が「外部」と判定され、direction が transit になる。
    -- ルータの RA が広告しているプレフィックスを確認して、次の行を有効にする:
    --   , ('2001:db8:aaaa:bbbb::/64', 'LAN (IPv6)')
ON CONFLICT (prefix) DO NOTHING;

CREATE OR REPLACE FUNCTION is_internal(ip inet)
RETURNS boolean
LANGUAGE sql STABLE AS $$
    SELECT EXISTS (SELECT 1 FROM lan_prefix p WHERE ip <<= p.prefix::inet);
$$;

-- kept for backwards compatibility with ad-hoc queries
CREATE OR REPLACE FUNCTION is_private(ip inet)
RETURNS boolean
LANGUAGE sql STABLE AS $$
    SELECT is_internal(ip);
$$;

-- ---------------------------------------------------------------------------
-- 5. Resolved IP -> ASN dictionary
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ip_asn (
    ip          inet PRIMARY KEY,
    asn         BIGINT NOT NULL DEFAULT 0,
    org         TEXT   NOT NULL DEFAULT '',
    country     TEXT   NOT NULL DEFAULT '',
    is_internal boolean NOT NULL DEFAULT false,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- for databases created before is_internal existed
ALTER TABLE ip_asn ADD COLUMN IF NOT EXISTS is_internal BOOLEAN NOT NULL DEFAULT false;

CREATE INDEX IF NOT EXISTS ip_asn_updated_idx ON ip_asn (updated_at);

CREATE OR REPLACE FUNCTION refresh_ip_asn(p_lookback INTERVAL DEFAULT '2 days')
RETURNS INTEGER
LANGUAGE plpgsql AS $$
DECLARE
    inserted INTEGER;
BEGIN
    INSERT INTO ip_asn (ip, asn, org, country, is_internal)
    SELECT s.ip,
           COALESCE(a.asn, 0),
           COALESCE(a.org, ''),
           COALESCE(a.country, ''),
           is_internal(s.ip)
    FROM (
        SELECT DISTINCT ip
        FROM (
            SELECT ip_src AS ip FROM flows
             WHERE stamp_inserted >= (now() AT TIME ZONE 'utc') - p_lookback
            UNION
            SELECT ip_dst AS ip FROM flows
             WHERE stamp_inserted >= (now() AT TIME ZONE 'utc') - p_lookback
        ) u
        WHERE ip <> '0.0.0.0'::inet AND ip <> '::'::inet
    ) s
    LEFT JOIN LATERAL asn_lookup(ip2num(s.ip)) a ON true
    ON CONFLICT (ip) DO NOTHING;

    GET DIAGNOSTICS inserted = ROW_COUNT;
    RETURN inserted;
END;
$$;

-- ---------------------------------------------------------------------------
-- 6. Decapsulated MAP-E flows
--
-- pmacct cannot decode IPv4-in-IPv6 for sFlow, so optional/decapd/decapd.py
-- parses the sampled header itself and writes the inner 5-tuple here. Rows are
-- deltas: the writer adds into existing buckets with ON CONFLICT DO UPDATE.
-- The table stays empty unless the stack was installed with --with-decapd.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS flows_decap (
    bucket     TIMESTAMP NOT NULL,
    ip_src     inet      NOT NULL,
    ip_dst     inet      NOT NULL,
    port_src   INT       NOT NULL,
    port_dst   INT       NOT NULL,
    ip_proto   SMALLINT  NOT NULL,
    packets    BIGINT    NOT NULL,
    bytes      BIGINT    NOT NULL,
    samples    BIGINT    NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (bucket, ip_src, ip_dst, port_src, port_dst, ip_proto)
);

CREATE INDEX IF NOT EXISTS flows_decap_bucket_idx ON flows_decap (bucket DESC);

-- ---------------------------------------------------------------------------
-- 6b. Enriched detail view
--
--   outbound = internal -> external
--   inbound  = external -> internal
--   internal = internal <-> internal
--   transit  = external -> external
--
-- "internal" membership comes from lan_prefix (RFC1918 + the LAN IPv6 /64),
-- so IPv6 hosts are classified correctly. Both the ASN and the internal flag
-- come from the ip_asn dictionary; a miss is resolved inline by the COALESCE
-- branches, which are only evaluated for rows that actually missed.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW v_flows AS
WITH raw AS (
    -- outer MAP-E records (proto 4) are replaced by their decapsulated inner
    -- flow, otherwise the same bytes would be counted twice
    SELECT f.stamp_inserted AS bucket, f.ip_src, f.ip_dst, f.port_src, f.port_dst,
           f.ip_proto, f.packets::bigint AS packets, f.bytes,
           f.flows::bigint AS flows, false AS decapped
    FROM flows f
    WHERE f.ip_proto <> 4
       -- keep the outer record while nothing has been decapsulated for that
       -- bucket yet (decapd not running, or just started mid-bucket), so the
       -- traffic never silently disappears
       OR NOT EXISTS (SELECT 1 FROM flows_decap d WHERE d.bucket = f.stamp_inserted)
    UNION ALL
    SELECT d.bucket, d.ip_src, d.ip_dst, d.port_src, d.port_dst,
           d.ip_proto, d.packets, d.bytes, d.samples, true
    FROM flows_decap d
),
cached AS (
    SELECT
        f.bucket,
        f.ip_src,
        f.ip_dst,
        f.port_src,
        f.port_dst,
        least(nullif(f.port_src, 0), nullif(f.port_dst, 0)) AS svc_port,
        f.ip_proto,
        f.packets,
        f.bytes,
        f.flows,
        f.decapped,
        s.is_internal AS c_src_int, s.asn AS c_src_asn,
        s.org AS c_src_org, s.country AS c_src_cc,
        d.is_internal AS c_dst_int, d.asn AS c_dst_asn,
        d.org AS c_dst_org, d.country AS c_dst_cc
    FROM raw f
    LEFT JOIN ip_asn s ON s.ip = f.ip_src
    LEFT JOIN ip_asn d ON d.ip = f.ip_dst
),
resolved AS (
    SELECT
        c.*,
        COALESCE(c.c_src_int, is_internal(c.ip_src)) AS s_int,
        COALESCE(c.c_dst_int, is_internal(c.ip_dst)) AS d_int
    FROM cached c
)
SELECT
    c.bucket,
    c.ip_src,
    c.ip_dst,
    c.port_src,
    c.port_dst,
    c.svc_port,
    c.ip_proto,
    proto_name(c.ip_proto) AS proto,
    c.packets,
    c.bytes,
    c.flows,
    s_int AS src_internal,
    d_int AS dst_internal,
    CASE
        -- decapd only ever sees WAN-ingress samples: those are downloads
        WHEN c.decapped THEN 'inbound'
        WHEN s_int AND NOT d_int THEN 'outbound'
        WHEN d_int AND NOT s_int THEN 'inbound'
        WHEN s_int AND d_int     THEN 'internal'
        ELSE 'transit'
    END AS direction,
    -- MAP-E / DS-Lite expose only the outer IPv6 header in sFlow (protocol 4),
    -- so the inner IPv4 5-tuple is not recoverable. Detecting this beats
    -- silently attributing the traffic to the BR's transit AS.
    CASE WHEN c.ip_proto = 4 THEN -1
         ELSE COALESCE(c.c_src_asn, (SELECT a.asn FROM asn_lookup(ip2num(c.ip_src)) a), 0) END AS src_asn,
    CASE WHEN c.ip_proto = 4 THEN 'MAP-E (IPv4-in-IPv6)'
         ELSE COALESCE(c.c_src_org, (SELECT a.org FROM asn_lookup(ip2num(c.ip_src)) a), '') END AS src_org,
    COALESCE(c.c_src_cc,  (SELECT a.country FROM asn_lookup(ip2num(c.ip_src)) a), '') AS src_cc,
    CASE WHEN c.ip_proto = 4 THEN -1
         WHEN c.decapped THEN -2
         ELSE COALESCE(c.c_dst_asn, (SELECT a.asn FROM asn_lookup(ip2num(c.ip_dst)) a), 0) END AS dst_asn,
    CASE WHEN c.ip_proto = 4 THEN 'MAP-E (IPv4-in-IPv6)'
         WHEN c.decapped THEN '(MAP-E 経由のダウンロード)'
         ELSE COALESCE(c.c_dst_org, (SELECT a.org FROM asn_lookup(ip2num(c.ip_dst)) a), '') END AS dst_org,
    COALESCE(c.c_dst_cc,  (SELECT a.country FROM asn_lookup(ip2num(c.ip_dst)) a), '') AS dst_cc
FROM resolved c;

-- ---------------------------------------------------------------------------
-- 7. Rollup read by the dashboards
--
-- Private addresses are kept as hosts (that is the interesting dimension);
-- public addresses collapse to their ASN, so cardinality stays bounded no
-- matter how much traffic passes (0.0.0.0 = "not a private host").
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS flow_5m (
    bucket     TIMESTAMP NOT NULL,
    direction  TEXT      NOT NULL,
    src_asn    BIGINT    NOT NULL,
    dst_asn    BIGINT    NOT NULL,
    src_org    TEXT      NOT NULL DEFAULT '',
    dst_org    TEXT      NOT NULL DEFAULT '',
    src_host   inet      NOT NULL DEFAULT '0.0.0.0',
    dst_host   inet      NOT NULL DEFAULT '0.0.0.0',
    svc_port   INT       NOT NULL DEFAULT 0,
    bytes      BIGINT    NOT NULL,
    packets    BIGINT    NOT NULL,
    samples    BIGINT    NOT NULL,
    PRIMARY KEY (bucket, direction, src_asn, dst_asn, src_host, dst_host, svc_port)
);

CREATE INDEX IF NOT EXISTS flow_5m_bucket_idx ON flow_5m (bucket DESC);

-- Recompute everything from p_since onwards. Runs inside one transaction, so
-- readers always see either the old or the new version of the window.
CREATE OR REPLACE FUNCTION refresh_flow_5m(p_since TIMESTAMP DEFAULT NULL)
RETURNS INTEGER
LANGUAGE plpgsql AS $$
DECLARE
    since   TIMESTAMP := COALESCE(p_since, date_trunc('minute', (now() AT TIME ZONE 'utc')) - interval '90 minutes');
    written INTEGER;
BEGIN
    DELETE FROM flow_5m WHERE bucket >= since;

    INSERT INTO flow_5m (bucket, direction, src_asn, dst_asn, src_org, dst_org,
                         src_host, dst_host, svc_port, bytes, packets, samples)
    SELECT
        f.bucket,
        f.direction,
        f.src_asn,
        f.dst_asn,
        min(f.src_org),
        min(f.dst_org),
        CASE WHEN f.src_internal THEN f.ip_src ELSE '0.0.0.0'::inet END,
        CASE WHEN f.dst_internal THEN f.ip_dst ELSE '0.0.0.0'::inet END,
        COALESCE(f.svc_port, 0),
        sum(f.bytes),
        sum(f.packets),
        count(*)
    FROM v_flows f
    WHERE f.bucket >= since
    GROUP BY 1, 2, 3, 4, 7, 8, 9;

    GET DIAGNOSTICS written = ROW_COUNT;
    RETURN written;
END;
$$;

-- ---------------------------------------------------------------------------
-- 8. Sankey helper
--
-- Returns exactly (source, target, value) in the shape Grafana's Sankey panel
-- expects, already chained as SRC -> DST -> SERVICE.
--
-- Node names are namespaced ("S|", "D|", "P|") so the same ASN showing up as
-- both source and destination becomes two nodes and cannot create a cycle
-- (d3-sankey refuses to draw cyclic graphs).
-- p_direction: 'all' | 'outbound' | 'inbound' | 'internal'
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION sankey_flows(
    p_from      TIMESTAMP,
    p_to        TIMESTAMP,
    p_direction TEXT DEFAULT 'all',
    p_limit     INT  DEFAULT 12
)
RETURNS TABLE (source TEXT, target TEXT, value NUMERIC)
LANGUAGE sql STABLE AS $$
WITH agg AS (
    SELECT
        CASE WHEN g.src_host <> '0.0.0.0'::inet THEN 'S|' || host(g.src_host)
             WHEN g.src_asn > 0 THEN 'S|AS' || g.src_asn || ' ' || g.src_org
             WHEN g.src_org <> '' THEN 'S|' || g.src_org
             ELSE 'S|(unresolved)' END AS src_node,
        CASE WHEN g.dst_host <> '0.0.0.0'::inet THEN 'D|' || host(g.dst_host)
             WHEN g.dst_asn > 0 THEN 'D|AS' || g.dst_asn || ' ' || g.dst_org
             WHEN g.dst_org <> '' THEN 'D|' || g.dst_org
             ELSE 'D|(unresolved)' END AS dst_node,
        CASE WHEN g.svc_port = 0 THEN 'P|(no port)'
             ELSE 'P|:' || g.svc_port END AS svc_node,
        sum(g.bytes) AS bytes
    FROM flow_5m g
    WHERE g.bucket >= p_from
      AND g.bucket <  p_to
      -- 'すべて' is the dashboard's display text; accept it so that an old
      -- bookmarked URL (var-direction=すべて) still renders instead of
      -- silently returning zero rows
      AND (p_direction IN ('all', 'すべて') OR g.direction = p_direction)
    GROUP BY 1, 2, 3
),
top_src AS (
    SELECT src_node FROM agg GROUP BY 1 ORDER BY sum(bytes) DESC LIMIT p_limit
),
top_dst AS (
    SELECT dst_node FROM agg GROUP BY 1 ORDER BY sum(bytes) DESC LIMIT p_limit
),
-- the service column fragments easily (dozens of ephemeral ports). Collapse it
-- to the busiest ports, otherwise the right-hand column is unreadable.
top_svc AS (
    -- hard cap: more than ~8 port nodes makes the right column unreadable
    SELECT svc_node FROM agg GROUP BY 1 ORDER BY sum(bytes) DESC
    LIMIT LEAST(p_limit, 8)
),
norm AS (
    SELECT
        CASE WHEN ts.src_node IS NULL THEN 'S|(other)' ELSE a.src_node END AS src_node,
        CASE WHEN td.dst_node IS NULL THEN 'D|(other)' ELSE a.dst_node END AS dst_node,
        COALESCE(tv.svc_node, 'P|(other)') AS svc_node,
        a.bytes
    FROM agg a
    LEFT JOIN top_src ts ON ts.src_node = a.src_node
    LEFT JOIN top_dst td ON td.dst_node = a.dst_node
    LEFT JOIN top_svc tv ON tv.svc_node = a.svc_node
),
links AS (
    SELECT src_node AS source, dst_node AS target, sum(bytes) AS bytes FROM norm GROUP BY 1, 2
    UNION ALL
    SELECT dst_node AS source, svc_node AS target, sum(bytes) AS bytes FROM norm GROUP BY 1, 2
)
SELECT source, target, sum(bytes)::numeric FROM links GROUP BY 1, 2;
$$;

-- ---------------------------------------------------------------------------
-- 9. Retention
--   raw flow rows are only needed for a few days (detail / forensics)
--   the rollup is what dashboards read, keep it much longer
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION prune_traffic(
    p_keep_flows INTERVAL DEFAULT '7 days',
    p_keep_rollup INTERVAL DEFAULT '45 days'
)
RETURNS TABLE (deleted_flows BIGINT, deleted_rollup BIGINT)
LANGUAGE plpgsql AS $$
DECLARE
    n_flows  BIGINT;
    n_rollup BIGINT;
BEGIN
    DELETE FROM flows
     WHERE stamp_inserted < (now() AT TIME ZONE 'utc') - p_keep_flows;
    GET DIAGNOSTICS n_flows = ROW_COUNT;

    DELETE FROM flow_5m
     WHERE bucket < (now() AT TIME ZONE 'utc') - p_keep_rollup;
    GET DIAGNOSTICS n_rollup = ROW_COUNT;

    RETURN QUERY SELECT n_flows, n_rollup;
END;
$$;

